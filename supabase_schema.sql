-- STORM Studio: complete Supabase schema (including separate hosting plans and subscriptions)
-- Run this whole file once in Supabase Dashboard -> SQL Editor -> New query.
-- The service-role key must remain on the server (Dokploy), never in public browser code.

begin;

create table if not exists public.storm_studio_meta (
  id text primary key check (id = 'main'),
  schema_version integer not null default 1,
  created_at timestamptz not null default now()
);

create table if not exists public.storm_studio_services (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.storm_studio_projects (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.storm_studio_orders (
  id text primary key,
  data jsonb not null,
  session_id text,
  telegram_id text,
  status text,
  payment_status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.storm_studio_hosting_plans (
  id text primary key,
  data jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.storm_studio_hosting_subscriptions (
  id text primary key,
  data jsonb not null,
  serial_id bigint,
  session_id text,
  telegram_id text,
  status text,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists storm_studio_hosting_subscriptions_serial_idx
  on public.storm_studio_hosting_subscriptions (serial_id) where serial_id is not null;
create index if not exists storm_studio_hosting_subscriptions_customer_idx
  on public.storm_studio_hosting_subscriptions (telegram_id, session_id);

create table if not exists public.storm_studio_settings (
  id text primary key check (id = 'main'),
  data jsonb not null,
  updated_at timestamptz not null default now()
);

create index if not exists storm_studio_orders_created_at_idx
  on public.storm_studio_orders (created_at desc);
create index if not exists storm_studio_orders_telegram_id_idx
  on public.storm_studio_orders (telegram_id);
create index if not exists storm_studio_orders_session_id_idx
  on public.storm_studio_orders (session_id);
create index if not exists storm_studio_orders_status_idx
  on public.storm_studio_orders (status);

