-- Only the backend service role can access the application tables directly.
alter table public.storm_studio_meta enable row level security;
alter table public.storm_studio_services enable row level security;
alter table public.storm_studio_projects enable row level security;
alter table public.storm_studio_orders enable row level security;
alter table public.storm_studio_hosting_plans enable row level security;
alter table public.storm_studio_hosting_subscriptions enable row level security;
alter table public.storm_studio_settings enable row level security;

revoke all on table public.storm_studio_meta from anon, authenticated;
revoke all on table public.storm_studio_services from anon, authenticated;
revoke all on table public.storm_studio_projects from anon, authenticated;
revoke all on table public.storm_studio_orders from anon, authenticated;
revoke all on table public.storm_studio_hosting_plans from anon, authenticated;
revoke all on table public.storm_studio_hosting_subscriptions from anon, authenticated;
revoke all on table public.storm_studio_settings from anon, authenticated;

grant all on table public.storm_studio_meta to service_role;
grant all on table public.storm_studio_services to service_role;
grant all on table public.storm_studio_projects to service_role;
grant all on table public.storm_studio_orders to service_role;
grant all on table public.storm_studio_hosting_plans to service_role;
grant all on table public.storm_studio_hosting_subscriptions to service_role;
grant all on table public.storm_studio_settings to service_role;

-- A single SQL transaction stores the application's current state across the tables.
-- This mirrors the small app's in-memory state while keeping all persistent data in Supabase.
create or replace function public.storm_studio_save_state(p_state jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  now_at timestamptz := now();
begin
  if p_state is null or jsonb_typeof(p_state) <> 'object' then
    raise exception 'Invalid STORM Studio state payload';
  end if;

  delete from public.storm_studio_services where id is not null;
  insert into public.storm_studio_services (id, data, created_at, updated_at)
  select item ->> 'id', item, now_at, now_at
  from jsonb_array_elements(coalesce(p_state -> 'services', '[]'::jsonb)) as service_item(item)
  where jsonb_typeof(item) = 'object' and nullif(item ->> 'id', '') is not null;

  delete from public.storm_studio_hosting_plans where id is not null;
  insert into public.storm_studio_hosting_plans (id, data, created_at, updated_at)
  select item ->> 'id', item, now_at, now_at
  from jsonb_array_elements(coalesce(p_state -> 'hostingPlans', '[]'::jsonb)) as hosting_plan_item(item)
  where jsonb_typeof(item) = 'object' and nullif(item ->> 'id', '') is not null;

  delete from public.storm_studio_hosting_subscriptions where id is not null;
  insert into public.storm_studio_hosting_subscriptions (
    id, data, serial_id, session_id, telegram_id, status, expires_at, created_at, updated_at
  )
  select
    item ->> 'id', item,
    nullif(item ->> 'serialId', '')::bigint,
    nullif(item ->> 'sessionId', ''),
    nullif(item ->> 'telegramId', ''),
    nullif(item ->> 'status', ''),
    nullif(item ->> 'expiresAt', '')::timestamptz,
    coalesce(nullif(item ->> 'createdAt', '')::timestamptz, now_at),
    coalesce(nullif(item ->> 'updatedAt', '')::timestamptz, now_at)
  from jsonb_array_elements(coalesce(p_state -> 'hostingSubscriptions', '[]'::jsonb)) as hosting_subscription_item(item)
  where jsonb_typeof(item) = 'object' and nullif(item ->> 'id', '') is not null;

  delete from public.storm_studio_projects where id is not null;
  insert into public.storm_studio_projects (id, data, created_at, updated_at)
  select item ->> 'id', item, now_at, now_at
  from jsonb_array_elements(coalesce(p_state -> 'projects', '[]'::jsonb)) as project_item(item)
  where jsonb_typeof(item) = 'object' and nullif(item ->> 'id', '') is not null;

  delete from public.storm_studio_orders where id is not null;
  insert into public.storm_studio_orders (
    id, data, session_id, telegram_id, status, payment_status, created_at, updated_at
  )
  select
    item ->> 'id',
    item,
    nullif(item ->> 'sessionId', ''),
    nullif(item ->> 'telegramId', ''),
    nullif(item ->> 'status', ''),
    nullif(item ->> 'paymentStatus', ''),
    coalesce(nullif(item ->> 'createdAt', '')::timestamptz, now_at),
    coalesce(nullif(item ->> 'updatedAt', '')::timestamptz, now_at)
  from jsonb_array_elements(coalesce(p_state -> 'orders', '[]'::jsonb)) as order_item(item)
  where jsonb_typeof(item) = 'object' and nullif(item ->> 'id', '') is not null;

  insert into public.storm_studio_settings (id, data, updated_at)
  values ('main', coalesce(p_state -> 'settings', '{}'::jsonb), now_at)
  on conflict (id) do update
    set data = excluded.data,
        updated_at = excluded.updated_at;

  insert into public.storm_studio_meta (id, schema_version, created_at)
  values ('main', coalesce(nullif(p_state ->> 'schemaVersion', '')::integer, 1), now_at)
  on conflict (id) do update
    set schema_version = greatest(public.storm_studio_meta.schema_version, excluded.schema_version);
end;
$$;

revoke all on function public.storm_studio_save_state(jsonb) from public, anon, authenticated;
grant execute on function public.storm_studio_save_state(jsonb) to service_role;

commit;
